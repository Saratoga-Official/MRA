# -*- coding: utf-8 -*-
# 存放"需要跨任务/跨循环记住"的状态。
属性列表 = ["火力", "鱼雷", "装甲", "对空"]
已耗尽属性 = set()
当前船可强化属性 = []
当前船名 = ""

# 累加器：{key: 累计值}，进程内持久，跨任务不丢
累加值 = {}


def 重置():
    """开始一次完整强化任务前调用，清空强化相关的记忆。

    注意：不清 累加值。累加是跨任务统计，不跟着每轮任务清零。
    需要清累加时请显式调用 重置累加()。
    """
    已耗尽属性.clear()
    当前船可强化属性.clear()
    global 当前船名
    当前船名 = ""


def 重置累加():
    """清空累加值。用于需要重新开始统计的场景。"""
    累加值.clear()


def 累加(key: str, value: float) -> float:
    """把 value 加到 key 上，返回累加后的值。"""
    累加值[key] = 累加值.get(key, 0) + value
    return 累加值[key]